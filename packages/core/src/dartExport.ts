import type { Model, Project } from './schema';

/**
 * Generates idiomatic Dart classes for models in the project.
 */
export function exportModelToDart(model: Model): string {
  const className = model.name;
  const fields = model.fields;

  const fieldDecls = fields
    .map((f) => `  final ${f.type}${f.nullable ? '?' : ''} ${f.name};`)
    .join('\n');

  const constructorParams = fields
    .map((f) => (f.nullable ? `    this.${f.name},` : `    required this.${f.name},`))
    .join('\n');

  const fromJsonFields = fields
    .map((f) => {
      // Basic type casting
      return `      ${f.name}: json['${f.name}'] as ${f.type}${f.nullable ? '?' : ''},`;
    })
    .join('\n');

  const toJsonFields = fields
    .map((f) => `      '${f.name}': ${f.name},`)
    .join('\n');

  return `class ${className} {
${fieldDecls}

  const ${className}({
${constructorParams}
  });

  factory ${className}.fromJson(Map<String, dynamic> json) => ${className}(
${fromJsonFields}
  );

  Map<String, dynamic> toJson() => {
${toJsonFields}
  };
}
`;
}

export function exportAllModelsToDart(project: Project): string {
  const parts = project.models.map((m) => exportModelToDart(m));
  return `// Generated by EventFlow
// Project: ${project.name}

${parts.join('\n\n')}
`;
}
